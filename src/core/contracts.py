"""Data contracts and shared structures for Procedural Keystroke Synth.
High-performance, low-latency inter-thread event structures.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum, auto
import time


class KeyType(Enum):
    RHYTHM = auto()         # Alphanumeric typing -> melodic/percussive arpeggio pulses
    CHORD_SHIFT = auto()    # Brackets, punctuation, indentation -> harmonic chord changes
    BACKSPACE_LPF = auto()  # Backspace/Delete -> drops LPF filter cutoff (muffled, rewind effect)
    ENTER_BASS = auto()     # Enter/Return -> triggers sub-bass drop / resolve
    NAVIGATION = auto()     # Arrows, PageUp/Down, Home/End -> subtle panning or texture shifts
    MODIFIER = auto()       # Shift, Ctrl, Alt -> texture shimmer / envelope modulation
    IGNORE = auto()         # Unmapped or noise keys


from typing import Optional


@dataclass(frozen=True, slots=True)
class KeyEvent:
    """Telemetry event generated by Agent-Input on OS key press."""
    timestamp: float                # time.monotonic() timestamp
    key_type: str                   # "regular", "modulation", "backspace", "enter"
    raw_char: Optional[str]         # Character or representation of key
    wpm: float                      # Current rolling WPM


@dataclass(frozen=True, slots=True)
class HarmonyEvent:
    """Harmonic audio trigger generated by Agent-Harmony."""
    event_type: str                 # "note", "sub_drop", "lpf_update"
    frequency: float                # Frequency in Hz
    velocity: float                 # 0.0 .. 1.0
    lpf_cutoff: float               # Filter cutoff (normalized 0.1 .. 1.0 or Hz)
    duration: float                 # Duration in seconds
    timestamp: float                # time.monotonic() timestamp


@dataclass(slots=True)
class PlaybackState:
    """Harmonic and audio macro-parameters generated by Agent-Harmony."""
    wpm: float = 0.0                    # Rolling words-per-minute (EMA or sliding window)
    target_bpm: float = 75.0            # Dynamic tempo mapped from WPM (e.g., 60-120 BPM)
    scale_root: int = 62                # Root MIDI note (62 = D4)
    scale_type: str = "dorian"          # Musical scale/mode ("dorian", "minor_pentatonic")
    lpf_cutoff: float = 8000.0          # Low-pass filter cutoff in Hz (300.0 - 16000.0)
    reverb_send: float = 0.25           # Wet send ratio [0.0, 1.0]
    trigger_sub: bool = False           # Flag to trigger sub-bass burst (consumed by DSP)
    active_chord: list[int] = field(default_factory=lambda: [62, 65, 69, 72]) # Active chord MIDI pitches


@dataclass(slots=True)
class AudioVoice:
    """Preallocated voice slot in the DSP pool (zero memory allocations in audio thread)."""
    frequency: float = 0.0          # Oscillator frequency in Hz
    phase: float = 0.0              # Current phase accumulator [0, 2*pi)
    amplitude: float = 0.0          # Current instantaneous amplitude [0.0, 1.0]
    decay_rate: float = 0.9995      # Per-sample multiplicative decay or envelope coefficient
    voice_type: str = "ambient_sine"# Voice timbre ("ambient_sine", "sub_bass", "click_transient")
    is_active: bool = False         # Quick state check for voice allocator
    note_id: int = -1               # Track MIDI note or key origin
